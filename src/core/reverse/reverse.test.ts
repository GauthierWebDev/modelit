const reverse = (sql: string) => reverseEngineer(sql, emptyDocument());
const mldOf = (sql: string) => mldPlainText(toLogicalModel(reverse(sql).doc));

describe("lecture multi-dialectes (override O-28)", () => {
  it("PostgreSQL (pg_dump) : ALTER TABLE ONLY, séquences, fonctions et CHECK ignorés", () => {
    const sql = `
      SET statement_timeout = 0;
      CREATE FUNCTION public.touch() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated := now(); RETURN NEW; END; $$;
      CREATE TABLE public.client (
        id integer NOT NULL,
        nom character varying(80) NOT NULL,
        email text,
        CONSTRAINT nom_non_vide CHECK ((char_length(nom) > 0))
      );
      CREATE SEQUENCE public.client_id_seq AS integer START WITH 1;
      ALTER TABLE ONLY public.client ALTER COLUMN id SET DEFAULT nextval('public.client_id_seq'::regclass);
      ALTER TABLE ONLY public.client ADD CONSTRAINT client_pkey PRIMARY KEY (id);
      CREATE TABLE public.commande (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id integer NOT NULL, passee_le timestamp with time zone);
      ALTER TABLE ONLY public.commande ADD CONSTRAINT commande_client_fk FOREIGN KEY (client_id) REFERENCES public.client(id) ON DELETE CASCADE;
      CREATE INDEX commande_client_idx ON public.commande USING btree (client_id);
      CREATE VIEW v AS SELECT 1;
      CREATE TRIGGER t BEFORE UPDATE ON public.client FOR EACH ROW EXECUTE FUNCTION public.touch();
      COMMENT ON TABLE public.client IS 'Clients actifs';
    `;
    const { doc, report } = reverse(sql);
    expect(report.tables).toBe(2);
    expect(report.warnings).toEqual([]);
    // Déclencheur conservé tel quel (O-35) et séquence lue (O-39) : plus comptés parmi les instructions ignorées.
    expect(report.ignored).toBeGreaterThanOrEqual(3);
    const client = doc.entities.find((e) => e.name === "client")!;
    expect(client.triggers).toEqual([expect.objectContaining({ name: "t", dialect: "postgresql" })]);
    expect(client.comment).toBe("Clients actifs");
    expect(client.attributes[0]).toMatchObject({ name: "id", identifier: true, type: { kind: "counter" } });
    expect(client.attributes[1]).toMatchObject({
      name: "nom",
      notNull: true,
      type: { kind: "text", length: "variable", size: 80 },
    });
    expect(mldOf(sql)).toBe("client = (_id_, nom, email);\ncommande = (_id_, #client_id, passee_le);");
    const commande = doc.entities.find((e) => e.name === "commande")!;
    expect(commande.attributes.find((a) => a.name === "passee_le")!.type).toEqual({
      kind: "datetime",
      withTimeZone: true,
    });
    expect(doc.links.find((l) => l.entityId === commande.id)!.onDelete).toBe("cascade");
  });

  it("MySQL (mysqldump) : accents graves, AUTO_INCREMENT, options de table, KEY ignorés", () => {
    const sql = `
      /*!40101 SET NAMES utf8mb4 */;
      DROP TABLE IF EXISTS \`produit\`;
      CREATE TABLE \`produit\` (
        \`id\` int(11) unsigned NOT NULL AUTO_INCREMENT,
        \`libelle\` varchar(120) COLLATE utf8mb4_bin NOT NULL COMMENT 'Nom affiché',
        \`prix\` decimal(10,2) NOT NULL DEFAULT '0.00',
        \`actif\` tinyint(1) NOT NULL DEFAULT 1,
        \`maj\` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
        PRIMARY KEY (\`id\`),
        UNIQUE KEY \`uq_libelle\` (\`libelle\`),
        KEY \`idx_prix\` (\`prix\`),
        CONSTRAINT \`prix_positif\` CHECK (\`prix\` >= 0)
      ) ENGINE=InnoDB AUTO_INCREMENT=42 DEFAULT CHARSET=utf8mb4 COMMENT='Catalogue';
      INSERT INTO \`produit\` VALUES (1,'a',1.00,1,NULL);
    `;
    const { doc, report } = reverse(sql);
    expect(report.warnings).toEqual([]);
    const produit = doc.entities[0]!;
    expect(produit.comment).toBe("Catalogue");
    const [id, libelle, prix, actif] = produit.attributes;
    expect(id).toMatchObject({ identifier: true, type: { kind: "counter" } });
    expect(libelle).toMatchObject({
      unique: true,
      notNull: true,
      comment: "Nom affiché",
      type: { collation: "utf8mb4_bin" },
    });
    expect(prix).toMatchObject({
      type: { kind: "decimal", precision: 10, scale: 2 },
      defaultValue: { expression: "'0.00'", dialect: "mysql" },
    });
    expect(actif!.type).toEqual({ kind: "boolean" });
  });

  it("SQL Server : crochets, IDENTITY, GO, schémas dbo", () => {
    const sql = `
      CREATE TABLE [dbo].[Service] ([Id] [int] IDENTITY(1,1) NOT NULL, [Nom] [nvarchar](50) NOT NULL,
        CONSTRAINT [PK_Service] PRIMARY KEY CLUSTERED ([Id] ASC)) ON [PRIMARY]
      GO
      CREATE TABLE [dbo].[Employe] ([Id] INT IDENTITY PRIMARY KEY, [ServiceId] INT NULL REFERENCES [dbo].[Service]([Id]), [Photo] VARBINARY(MAX))
      GO
      EXEC sp_addextendedproperty 'MS_Description', 'x';
      GO
    `;
    const { doc } = reverse(sql);
    expect(doc.entities.map((e) => e.name)).toEqual(["Service", "Employe"]);
    expect(doc.entities[0]!.attributes[1]!.type).toEqual({
      kind: "text",
      encoding: "unicode",
      length: "variable",
      size: 50,
    });
    expect(doc.entities[1]!.attributes.find((a) => a.name === "Photo")!.type).toEqual({
      kind: "text",
      encoding: "binary",
      length: "large",
    });
    // FK nullable : 0,1 côté Employe
    expect(doc.links.find((l) => l.entityId === doc.entities[1]!.id)!.cardinality).toEqual({ min: 0, max: 1 });
  });

  it("Oracle : NUMBER, VARCHAR2, séparateur /, blocs PL/SQL ignorés", () => {
    const sql = `
      CREATE TABLE ville (code NUMBER(5) NOT NULL, nom VARCHAR2(60 CHAR), population NUMBER, CONSTRAINT pk_ville PRIMARY KEY (code));
      CREATE OR REPLACE TRIGGER trg BEFORE INSERT ON ville FOR EACH ROW
      BEGIN
        :new.nom := UPPER(:new.nom);
      END;
      /
      CREATE TABLE habitant (id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY, ville NUMBER(5) NOT NULL,
        CONSTRAINT pk_habitant PRIMARY KEY (id), CONSTRAINT fk_ville FOREIGN KEY (ville) REFERENCES ville (code));
    `;
    const { doc, report } = reverse(sql);
    expect(report.tables).toBe(2);
    const ville = doc.entities[0]!;
    // NUMBER(p) : p ≤ 4 → 16 bits, ≤ 9 → 32, ≤ 18 → 64 ; NUMBER sans précision : décimal libre, jamais un flottant (O-39).
    expect(ville.attributes.map((a) => a.type)).toEqual([
      { kind: "integer", bits: 32 },
      { kind: "text", encoding: "ascii", length: "variable", size: 60 },
      { kind: "decimal", scale: 0 },
    ]);
    expect(doc.entities[1]!.attributes[0]!.type).toEqual({ kind: "counter", bits: 64 });
    expect(doc.entities[1]!.attributes[0]!.identity).toBe("on null");
    expect(mldPlainText(toLogicalModel(doc))).toContain("habitant = (_id_, #ville);");
  });

  it("SQLite : INTEGER PRIMARY KEY AUTOINCREMENT", () => {
    const { doc } = reverse(
      "CREATE TABLE IF NOT EXISTS note (id INTEGER PRIMARY KEY AUTOINCREMENT, texte TEXT NOT NULL);",
    );
    expect(doc.entities[0]!.attributes[0]).toMatchObject({ identifier: true, type: { kind: "counter" } });
  });

  it("aucun élément inconnu ne provoque d'erreur", () => {
    const sql = "CREATE EXTENSION x; GRANT ALL ON t TO u; CREATE TYPE e AS ENUM ('a'); DO $$ BEGIN END $$; SELECT 1;";
    const { report } = reverse(sql);
    expect(report.tables).toBe(0);
    expect(report.warnings).toEqual([]);
    // CREATE TYPE … AS ENUM est lu (domaine des colonnes de ce type, O-35) : 4 instructions ignorées.
    expect(report.ignored).toBe(4);
  });

  it("clé étrangère vers une table absente : avertissement, pas d'erreur", () => {
    const { report } = reverse("CREATE TABLE a (id INT PRIMARY KEY, b_id INT REFERENCES b(id));");
    expect(report.warnings).toHaveLength(1);
  });
});

describe("reconstruction du MCD", () => {
  it("table d'association → association porteuse", () => {
    const sql = `
      CREATE TABLE commande (id INT PRIMARY KEY);
      CREATE TABLE produit (id INT PRIMARY KEY);
      CREATE TABLE ligne (commande_id INT REFERENCES commande(id), produit_id INT REFERENCES produit(id), quantite INT NOT NULL,
        PRIMARY KEY (commande_id, produit_id));
    `;
    const { doc } = reverse(sql);
    expect(doc.entities.map((e) => e.name)).toEqual(["commande", "produit"]);
    expect(doc.associations[0]).toMatchObject({ name: "ligne", attributes: [{ name: "quantite", notNull: true }] });
    expect(mldOf(sql)).toContain("ligne = (_#commande_id_, _#produit_id_, quantite);");
  });

  it("héritage : au moins deux tables de même clé que leur entité générique", () => {
    const sql = `
      CREATE TABLE personne (id INT PRIMARY KEY, nom VARCHAR(50));
      CREATE TABLE client (id INT PRIMARY KEY REFERENCES personne(id), remise DECIMAL(4,2));
      CREATE TABLE fournisseur (id INT PRIMARY KEY REFERENCES personne(id), siret CHAR(14));
    `;
    const { doc } = reverse(sql);
    expect(doc.inheritances).toHaveLength(1);
    expect(doc.inheritances[0]!.parentId).toBe(doc.entities[0]!.id);
    expect(mldOf(sql)).toBe("personne = (_id_, nom);\nclient = (_#id_, remise);\nfournisseur = (_#id_, siret);");
  });

  it("identifiant relatif", () => {
    const sql = `
      CREATE TABLE batiment (code CHAR(2) PRIMARY KEY);
      CREATE TABLE salle (batiment CHAR(2) REFERENCES batiment(code), numero INT, PRIMARY KEY (batiment, numero));
    `;
    const { doc } = reverse(sql);
    expect(doc.links.find((l) => l.relativeId)).toBeDefined();
    expect(mldOf(sql)).toContain("salle = (_#batiment_, _numero_);");
  });

  it("réflexive : la clé garde son nom", () => {
    const sql = "CREATE TABLE employe (id INT PRIMARY KEY, chef_id INT REFERENCES employe(id));";
    expect(mldOf(sql)).toBe("employe = (_id_, #chef_id);");
  });
});

describe("aller-retour SQL → MCD → SQL", () => {
  const roundTrip = (dbms: "postgresql" | "mysql" | "sqlserver" | "oracle" | "sqlite", version?: string) => {
    const doc = model()
      .entity("CLIENT", ["id_client*", "nom"])
      .entity("COMMANDE", ["num*"])
      .entity("PRODUIT", ["ref*", "libelle"])
      .entity("PERSONNE", ["id*"])
      .entity("SALARIE", ["matricule"])
      .entity("INTERIM", ["agence"])
      .entity("BATIMENT", ["code*"])
      .entity("SALLE", ["numero*"])
      .association("PASSER", ["CLIENT 0,n", "COMMANDE 1,1"])
      .association("CONTENIR", ["COMMANDE 1,n", "PRODUIT 0,n"], ["quantite"])
      .association("COMPORTER", ["BATIMENT 0,n", "SALLE 1,1(R)"])
      .inherit("PERSONNE", ["SALARIE", "INTERIM"])
      .typed("CLIENT", "id_client", { kind: "counter" })
      .typed("CLIENT", "nom", { kind: "text", encoding: "unicode", length: "variable", size: 80 })
      .typed("COMMANDE", "num", { kind: "integer", bits: 64 })
      .typed("PRODUIT", "ref", { kind: "text", encoding: "ascii", length: "fixed", size: 12 })
      .typed("PRODUIT", "libelle", { kind: "text", encoding: "ascii", length: "variable", size: 200 })
      .typed("PERSONNE", "id", { kind: "integer", bits: 32 })
      .typed("SALARIE", "matricule", { kind: "text", encoding: "ascii", length: "variable", size: 10 })
      .typed("INTERIM", "agence", { kind: "text", encoding: "ascii", length: "variable", size: 40 })
      .typed("BATIMENT", "code", { kind: "text", encoding: "ascii", length: "fixed", size: 2 })
      .typed("SALLE", "numero", { kind: "integer", bits: 16 })
      .build();
    doc.associations[1]!.attributes[0]!.type = { kind: "integer", bits: 32 };
    doc.settings.dbms = dbms;
    doc.settings.dbmsVersion = version ?? "generic";
    const first = generateDdl(toLogicalModel(doc), { dbms, version });
    expect(first.ok).toBe(true);
    const base = emptyDocument();
    base.settings = structuredClone(doc.settings);
    const { doc: back, report } = reverseEngineer(first.ok ? first.sql : "", base);
    expect(report.warnings).toEqual([]);
    expect(hasErrors(toLogicalModel(back))).toBe(false);
    expect(generateDdl(toLogicalModel(back), { dbms, version })).toEqual(first);
  };

  it("PostgreSQL 18", () => roundTrip("postgresql", "18"));
  it("PostgreSQL générique", () => roundTrip("postgresql"));
  it("MySQL", () => roundTrip("mysql", "8.4"));
  it("SQL Server", () => roundTrip("sqlserver", "2022"));
  it("Oracle", () => roundTrip("oracle", "23ai"));
  it("SQLite", () => roundTrip("sqlite"));
});

describe("Oracle : options de stockage d'un index (O-39)", () => {
  it("notées sur la table, donc au rapport", () => {
    const sql =
      "CREATE TABLE t (id NUMBER(5) PRIMARY KEY, c VARCHAR2(10 CHAR));\nCREATE UNIQUE INDEX ux_c ON t (c) TABLESPACE idx PCTFREE 5;";
    const result = generateDdl(toLogicalModel(reverseEngineer(sql, emptyDocument(), "oracle").doc), {
      dbms: "postgresql",
      version: "18",
    });
    expect(result.ok && result.losses).toContainEqual(
      expect.objectContaining({ table: "t", message: expect.stringContaining("INDEX TABLESPACE, INDEX PCTFREE") }),
    );
  });
});

describe("types", () => {
  it.each([
    ["VARCHAR(50)", { kind: "text", encoding: "ascii", length: "variable", size: 50 }],
    ["nvarchar(max)", { kind: "text", encoding: "unicode", length: "large" }],
    ["character varying(20)", { kind: "text", encoding: "ascii", length: "variable", size: 20 }],
    ["DOUBLE PRECISION", { kind: "real", precision: "double" }],
    ["timestamp without time zone", { kind: "datetime", withTimeZone: false }],
    ["uuid", { kind: "free", sql: "uuid" }],
    ["jsonb", { kind: "free", sql: "jsonb" }],
    ["BIT", { kind: "boolean" }],
  ] as const)("%s", (sql, expected) => {
    expect(sqlTypeToDataType(sql)).toEqual(expected);
  });

  it("le lecteur ne plante sur aucun texte", () => {
    for (const text of [
      "",
      "CREATE",
      "CREATE TABLE",
      "CREATE TABLE (",
      "CREATE TABLE t (a",
      "'unterminated",
      "$$ x",
      "ALTER TABLE",
    ]) {
      expect(() => parseSql(text)).not.toThrow();
    }
  });
});

describe("SGBD d'origine du modèle (O-55)", () => {
  it("repère le dialecte des rubriques rétroconçues", () => {
    const mysql = reverseEngineer(
      "CREATE TABLE t (id INT UNSIGNED PRIMARY KEY, etat ENUM('a','b'));",
      emptyDocument(),
      "mysql",
    ).doc;
    expect([...sourceDialects(mysql)]).toEqual(["mysql"]);
    const oracle = reverseEngineer("CREATE TABLE t (id NUMBER(4) PRIMARY KEY, d DATE);", emptyDocument(), "oracle").doc;
    expect([...sourceDialects(oracle)]).toEqual(["oracle"]);
  });

  it("ne trouve rien dans un modèle dessiné", () => {
    expect(sourceDialects(model().entity("Client", ["id_client*", "nom"]).build()).size).toBe(0);
  });
});
