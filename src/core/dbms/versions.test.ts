import { describe, expect, it } from "vitest";
import { deserializeModel, FILE_FORMAT } from "../io/modelFile";
import { MSG } from "../validation/messages";
import { sqlType } from "./typeMapping";
import {
  DBMS_VERSIONS,
  GENERIC_VERSION,
  isAtLeast,
  latestVersion,
  resolveVersion,
  versionFeatures,
  versionFeatureThresholds,
} from "./versions";

describe("versions des SGBD (override O-04)", () => {
  it("comparaison de versions", () => {
    expect(isAtLeast("postgresql", "16", "10")).toBe(true);
    expect(isAtLeast("postgresql", "9.6", "10")).toBe(false);
    expect(isAtLeast("postgresql", GENERIC_VERSION, "10")).toBe(false);
  });

  it.each([
    ["postgresql", "9.6", { kind: "counter" }, "SERIAL"],
    ["postgresql", "10", { kind: "counter" }, "INTEGER GENERATED BY DEFAULT AS IDENTITY"],
    ["postgresql", GENERIC_VERSION, { kind: "counter" }, "SERIAL"],
    ["oracle", "11g", { kind: "counter" }, "NUMBER(10)"],
    ["oracle", "19c", { kind: "counter" }, "NUMBER(10) GENERATED BY DEFAULT AS IDENTITY"],
    ["oracle", "21c", { kind: "boolean" }, "NUMBER(1)"],
    ["oracle", "23ai", { kind: "boolean" }, "BOOLEAN"],
  ] as const)("%s %s : %o → %s", (dbms, version, type, expected) => {
    expect(sqlType(type, dbms, version)).toBe(expected);
  });

  it("version invalide ou absente → la plus récente", () => {
    expect(resolveVersion("oracle", "16")).toBe(latestVersion("oracle"));
    expect(resolveVersion("oracle", GENERIC_VERSION)).toBe(GENERIC_VERSION);
  });

  it("un fichier sans version prend la plus récente de son SGBD", () => {
    const text = JSON.stringify({ format: FILE_FORMAT, version: 1, model: { settings: { dbms: "mysql" } } });
    expect(deserializeModel(text).doc.settings.dbmsVersion).toBe(latestVersion("mysql"));
  });

  it("ce qu'apporte une version (O-49)", () => {
    expect(versionFeatures("postgresql", "9.6")).toEqual([]);
    expect(versionFeatures("postgresql", "10")).toEqual([MSG.versionFeature.identity]);
    expect(versionFeatures("postgresql", "18")).toContain(MSG.versionFeature.uuidv7);
    expect(versionFeatures("oracle", "21c")).not.toContain(MSG.versionFeature.booleanType);
    expect(versionFeatures("oracle", "23ai")).toContain(MSG.versionFeature.booleanType);
    expect(versionFeatures("postgresql", GENERIC_VERSION)).toEqual([]);
  });

  it("chaque seuil est une version connue de son SGBD", () => {
    const unknown = versionFeatureThresholds().filter(
      ({ dbms, since }) => !DBMS_VERSIONS[dbms].some((v) => v.id === since),
    );
    expect(unknown).toEqual([]);
  });
});
