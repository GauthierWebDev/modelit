const TYPES: Record<string, DataType> = {
  ascii_var: { kind: "text", encoding: "ascii", length: "variable", size: 50 },
  ascii_fixe: { kind: "text", encoding: "ascii", length: "fixed", size: 50 },
  ascii_vol: { kind: "text", encoding: "ascii", length: "large" },
  uni_var: { kind: "text", encoding: "unicode", length: "variable", size: 50 },
  uni_fixe: { kind: "text", encoding: "unicode", length: "fixed", size: 50 },
  uni_vol: { kind: "text", encoding: "unicode", length: "large" },
  bin_vol: { kind: "text", encoding: "binary", length: "large" },
  int8: { kind: "integer", bits: 8 },
  int16: { kind: "integer", bits: 16 },
  int32: { kind: "integer", bits: 32 },
  int64: { kind: "integer", bits: 64 },
  real32: { kind: "real", precision: "single" },
  real64: { kind: "real", precision: "double" },
  money: { kind: "money" },
  counter: { kind: "counter" },
  time: { kind: "time" },
  datetime: { kind: "datetime", withTimeZone: false },
  bool: { kind: "boolean" },
  xml: { kind: "xml" },
  geom: { kind: "geometry" },
  geog: { kind: "geography" },
};

function parseTable(text: string) {
  const [header, ...rows] = text
    .trim()
    .split("\n")
    .map((l) =>
      l
        .split("|")
        .slice(1, -1)
        .map((c) => c.trim()),
    );
  return rows.map((cells) => Object.fromEntries(header!.map((h, i) => [h, cells[i]!])));
}

describe("correspondance des types", () => {
  for (const row of parseTable(FEATURE_13)) {
    it(`${row.sgbd}`, () => {
      for (const [column, type] of Object.entries(TYPES)) {
        expect(sqlType(type, row.sgbd as Dbms), column).toBe(row[column]);
      }
    });
  }

  it.each([
    ["access", "DATETIME"],
    ["mysql", "DATETIME"],
    ["mariadb", "DATETIME"],
    ["oracle", "TIMESTAMP WITH TIME ZONE"],
    ["postgresql", "TIMESTAMPTZ"],
    ["sqlserver", "DATETIMEOFFSET"],
    ["sybase", "TIMESTAMP WITH TIME ZONE"],
    ["db2", "TIMESTAMP"],
  ] as const)("date-heure avec fuseau : %s → %s", (dbms, expected) => {
    expect(sqlType({ kind: "datetime", withTimeZone: true }, dbms)).toBe(expected);
  });

  it.each([
    ["access", "VARBINARY(16)", "BINARY(16)"],
    ["mysql", "VARBINARY(16)", "BINARY(16)"],
    ["postgresql", "BIT VARYING(16)", "BIT(16)"],
    ["sqlserver", "VARBINARY(16)", "BINARY(16)"],
    ["sqlite", "TEXT", "TEXT"],
  ] as const)("binaire dimensionné : %s", (dbms, variable, fixed) => {
    expect(sqlType({ kind: "text", encoding: "binary", length: "variable", size: 16 }, dbms)).toBe(variable);
    expect(sqlType({ kind: "text", encoding: "binary", length: "fixed", size: 16 }, dbms)).toBe(fixed);
  });

  it("date : DATE partout sauf SQLite", () => {
    for (const dbms of ["access", "mysql", "mariadb", "oracle", "postgresql", "sqlserver", "sybase", "db2"] as const) {
      expect(sqlType({ kind: "date" }, dbms)).toBe("DATE");
    }
    expect(sqlType({ kind: "date" }, "sqlite")).toBe("NUMERIC");
  });

  it("collation et type libre", () => {
    expect(
      sqlType({ kind: "text", encoding: "ascii", length: "variable", size: 20, collation: "utf8mb4_bin" }, "mysql"),
    ).toBe("VARCHAR(20) COLLATE utf8mb4_bin");
    expect(sqlType({ kind: "free", sql: "JSONB" }, "oracle")).toBe("JSONB");
  });

  it("longueur absente : pas de parenthèses vides", () => {
    expect(sqlType({ kind: "text", encoding: "ascii", length: "variable" }, "postgresql")).toBe("VARCHAR");
  });

  it("une clé étrangère vers un compteur devient un entier", () => {
    expect(foreignKeyDataType({ kind: "counter" })).toEqual({ kind: "integer", bits: 32, counterKey: true });
    // Même type SQL que l'entier, sauf redéfinition par un SGBD personnalisé (O-59).
    expect(sqlType(foreignKeyDataType({ kind: "counter" })!, "postgresql", "18")).toBe("INTEGER");
    expect(sqlType(foreignKeyDataType({ kind: "counter", bits: 64 })!, "oracle", "19c")).toBe("NUMBER(20)");
    expect(sqlType(foreignKeyDataType({ kind: "counter" })!, "postgresql", "18", { counterForeignKey: "BIGINT" })).toBe(
      "BIGINT",
    );
  });
});
