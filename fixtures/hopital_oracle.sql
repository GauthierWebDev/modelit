-- Séquence « à l'ancienne », alimentée par trigger (voir fin de script)
CREATE SEQUENCE seq_sejour START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- T1 : nom non quoté (→ SERVICE), échelle négative, UNIQUE composite sur colonne
--      nullable (sémantique NULL propre à Oracle), clauses de stockage
CREATE TABLE service (
  code_service    VARCHAR2(6 CHAR),
  libelle         NVARCHAR2(100) NOT NULL,
  etage           NUMBER(2) CHECK (etage BETWEEN -3 AND 20),
  capacite        NUMBER(4) DEFAULT 0 NOT NULL,
  budget          NUMBER(12,-3),
  chef_id         NUMBER(10),
  service_parent  VARCHAR2(6 CHAR),
  actif           CHAR(1) DEFAULT 'O' NOT NULL,
  CONSTRAINT pk_service PRIMARY KEY (code_service)
    USING INDEX TABLESPACE users PCTFREE 5,
  CONSTRAINT uq_service_chef    UNIQUE (chef_id),
  CONSTRAINT uq_service_libelle UNIQUE (service_parent, libelle),
  CONSTRAINT ck_service_actif   CHECK (actif IN ('O', 'N'))
)
TABLESPACE users PCTFREE 10 STORAGE (INITIAL 64K NEXT 1M) LOGGING;

-- T2 : nom en casse mixte NON quoté (→ PERSONNEL), identité ON NULL,
--      VARCHAR2 en BYTE / CHAR / sans précision, booléen NUMBER(1), LOB
CREATE TABLE Personnel (
  matricule      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY
                 (START WITH 1000 INCREMENT BY 1 NOCACHE),
  nom            VARCHAR2(80 BYTE) NOT NULL,
  prenom         VARCHAR2(80 CHAR),
  email          VARCHAR2(254),
  fonction       VARCHAR2(20) NOT NULL,
  code_service   VARCHAR2(6 CHAR) NOT NULL,
  date_embauche  DATE DEFAULT SYSDATE NOT NULL,
  est_cadre      NUMBER(1) DEFAULT 0 NOT NULL,
  salaire        BINARY_DOUBLE,
  photo          BLOB,
  CONSTRAINT pk_personnel PRIMARY KEY (matricule),
  CONSTRAINT ck_personnel_fonction CHECK (fonction IN ('MEDECIN', 'INFIRMIER', 'ADMIN')),
  CONSTRAINT ck_personnel_cadre    CHECK (est_cadre IN (0, 1))
)
LOB (photo) STORE AS SECUREFILE (TABLESPACE users);

-- T3 : table et colonnes quotées (casse mixte, minuscules, espace), clé RAW/SYS_GUID,
--      FK inline (appliquée par Oracle) avec référence qualifiée par le schéma
CREATE TABLE "Patient" (
  "id"              RAW(16) DEFAULT SYS_GUID() NOT NULL,
  nir               CHAR(15) NOT NULL,
  nom               VARCHAR2(80) NOT NULL,
  date_naissance    DATE NOT NULL,
  sexe              CHAR(1),
  medecin_traitant  NUMBER(10) CONSTRAINT fk_patient_medecin
                    REFERENCES hopital.personnel (matricule) ON DELETE SET NULL,
  "Note libre"      CLOB,
  cree_le           TIMESTAMP(3) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  cree_par          VARCHAR2(128) DEFAULT USER NOT NULL,
  CONSTRAINT pk_patient     PRIMARY KEY ("id"),
  CONSTRAINT uq_patient_nir UNIQUE (nir),
  CONSTRAINT ck_patient_sexe CHECK (sexe IN ('M', 'F', 'X'))
);

-- T4 : NUMBER sans précision (alimenté par trigger), INTERVAL, colonne virtuelle
--      DATE + INTERVAL, CHECK différable, partitionnement par intervalle
CREATE TABLE sejour (
  sejour_id           NUMBER,
  patient_id          RAW(16) NOT NULL,
  code_service        VARCHAR2(6 CHAR) NOT NULL,
  date_entree         DATE NOT NULL,
  date_sortie         DATE,
  duree_prevue        INTERVAL DAY(3) TO SECOND(0),
  date_sortie_prevue  DATE GENERATED ALWAYS AS (date_entree + duree_prevue) VIRTUAL,
  motif               VARCHAR2(4000),
  CONSTRAINT pk_sejour PRIMARY KEY (sejour_id),
  CONSTRAINT ck_sejour_dates CHECK (date_sortie IS NULL OR date_sortie >= date_entree)
    DEFERRABLE INITIALLY DEFERRED
)
PARTITION BY RANGE (date_entree)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(PARTITION p_avant_2020 VALUES LESS THAN (DATE '2020-01-01'));

-- T5 : PK = FK + FK + colonne non-FK, colonne quotée en minuscules,
--      deux rôles vers PERSONNEL, contrainte désactivée
CREATE TABLE intervenir (
  sejour_id    NUMBER NOT NULL,
  matricule    NUMBER(10) NOT NULL,
  "type"       VARCHAR2(15) DEFAULT 'soin' NOT NULL,
  debut        TIMESTAMP(0) NOT NULL,
  duree        INTERVAL DAY(1) TO SECOND(0),
  superviseur  NUMBER(10),
  cout         NUMBER(8,2),
  CONSTRAINT pk_intervenir PRIMARY KEY (sejour_id, matricule, debut),
  CONSTRAINT ck_intervenir_type CHECK ("type" IN ('consult', 'chirurgie', 'soin')),
  CONSTRAINT ck_intervenir_cout CHECK (cout >= 0) DISABLE
);

-- ---------------------------------------------------------------------
--  Clés étrangères en ALTER TABLE (style Oracle), cycle SERVICE <-> PERSONNEL
-- ---------------------------------------------------------------------
ALTER TABLE service ADD CONSTRAINT fk_service_chef
  FOREIGN KEY (chef_id) REFERENCES personnel (matricule)
  DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE service ADD CONSTRAINT fk_service_parent
  FOREIGN KEY (service_parent) REFERENCES "SERVICE" (code_service)
  ON DELETE SET NULL;

ALTER TABLE PERSONNEL ADD CONSTRAINT fk_personnel_service
  FOREIGN KEY (code_service) REFERENCES service;

ALTER TABLE sejour ADD (
  CONSTRAINT fk_sejour_patient FOREIGN KEY (patient_id)
    REFERENCES "Patient" ("id") ON DELETE CASCADE,
  CONSTRAINT fk_sejour_service FOREIGN KEY (code_service)
    REFERENCES service (code_service)
);

ALTER TABLE intervenir ADD CONSTRAINT fk_intervenir_sejour
  FOREIGN KEY (sejour_id) REFERENCES sejour ON DELETE CASCADE;
ALTER TABLE intervenir ADD CONSTRAINT fk_intervenir_personnel
  FOREIGN KEY (matricule) REFERENCES personnel (matricule);
ALTER TABLE intervenir ADD CONSTRAINT fk_intervenir_superviseur
  FOREIGN KEY (superviseur) REFERENCES personnel (matricule) ON DELETE SET NULL;
ALTER TABLE intervenir ADD CONSTRAINT ck_intervenir_super
  CHECK (superviseur IS NULL OR superviseur <> matricule) ENABLE NOVALIDATE;

-- Index sur expression : unicité insensible à la casse, et unicité CONDITIONNELLE
CREATE UNIQUE INDEX ux_personnel_email ON personnel (LOWER(email));
CREATE UNIQUE INDEX ux_sejour_en_cours
  ON sejour (CASE WHEN date_sortie IS NULL THEN patient_id END);

-- Trigger PL/SQL terminé par « / » (SQL*Plus), WHEN sans « : » devant NEW
CREATE OR REPLACE TRIGGER trg_sejour_id
  BEFORE INSERT ON sejour
  FOR EACH ROW
  WHEN (NEW.sejour_id IS NULL)
BEGIN
  :NEW.sejour_id := seq_sejour.NEXTVAL;
END;
/

COMMENT ON TABLE service IS 'Services & pôles; ex. "Chirurgie & réa" / urgences';
COMMENT ON COLUMN service.budget IS 'Arrondi au millier (échelle négative)';
COMMENT ON COLUMN Personnel.salaire IS q'[Brut annuel; ni "primes" ni heures sup' (cf. RH)]';
COMMENT ON COLUMN "Patient"."Note libre" IS 'Texte libre -- ne pas /* parser */';

