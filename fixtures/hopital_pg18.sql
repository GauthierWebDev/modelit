-- Rapport de conversion vers PostgreSQL 18 : 27 élément(s) abandonné(s) ou dégradé(s)
--   • service.capacite — NUMBER(4) → SMALLINT : plage de valeurs élargie (aucun CHECK ne la borne)
--   • Oracle : '' vaut NULL ; ici, '' est une valeur distincte, stockée telle quelle : service.service_parent, Personnel.prenom, Personnel.email, Patient.Note libre, sejour.motif
--   • Personnel.matricule — identité ON NULL : un NULL explicite est refusé au lieu de recevoir une valeur
--   • Personnel.matricule — NUMBER(10) → BIGINT : plage de valeurs élargie (aucun CHECK ne la borne)
--   • Personnel.nom — VARCHAR2 / CHAR (n BYTE) : longueur en octets devenue longueur en caractères (plus de caractères multi-octets admis)
--   • VARCHAR2 / CHAR (n) sans BYTE ni CHAR : longueur en caractères ici ; dans la source, elle dépend de NLS_LENGTH_SEMANTICS (octets par défaut) : Personnel.email, Patient.nir, Patient.nom, Patient.cree_par, sejour.motif
--   • RAW(16) DEFAULT SYS_GUID() → UUID : approximation (mêmes 16 octets ; les valeurs de SYS_GUID ne sont pas des UUID normalisés) : Patient.id, sejour.patient_id
--   • Patient.id — DEFAULT SYS_GUID() → gen_random_uuid() : UUID aléatoire (version 4) au lieu de l'identifiant produit par Oracle
--   • Patient.sexe — Oracle : '' vaut NULL (acceptée) ; ici, '' est rejetée par le CHECK existant
--   • sejour.sejour_id — NUMBER → BIGINT : colonne alimentée par une séquence — décimales et valeurs au-delà de ±9,2 × 10¹⁸ refusées
--   • sejour.sejour_id — déclencheur de séquence → DEFAULT nextval : un NULL explicite n'est plus remplacé par une valeur de la séquence
--   • sejour.duree_prevue — INTERVAL DAY(3) TO SECOND(0) → INTERVAL DAY TO SECOND(0) : la précision des jours n'est plus bornée
--   • sejour — CHECK ck_sejour_dates différable → immédiat (CHECK jamais différable ici)
--   • sejour — partitionnement abandonné : PostgreSQL exige que la clé primaire contienne la clé de partition
--   • intervenir.duree — INTERVAL DAY(1) TO SECOND(0) → INTERVAL DAY TO SECOND(0) : la précision des jours n'est plus bornée
--   • intervenir — contrainte ck_intervenir_cout désactivée (DISABLE) dans la source : émise en commentaire, non appliquée
--   • clauses de stockage (USING INDEX, TABLESPACE, PCTFREE, STORAGE, LOGGING, LOB) abandonnées : sans effet sur les données : service, Personnel

CREATE SEQUENCE seq_sejour START WITH 1 INCREMENT BY 1 CACHE 1 NO CYCLE;

CREATE TABLE service(
   code_service VARCHAR(6) CHECK (code_service <> ''),
   libelle VARCHAR(100) NOT NULL CHECK (libelle <> ''),
   etage SMALLINT CHECK (etage BETWEEN -3 AND 20),
   capacite SMALLINT DEFAULT 0 NOT NULL,
   budget NUMERIC(12,-3),
   chef_id BIGINT,
   service_parent VARCHAR(6),
   actif CHAR(1) DEFAULT 'O' NOT NULL CONSTRAINT ck_service_actif CHECK (actif IN ('O', 'N')),
   CONSTRAINT pk_service PRIMARY KEY(code_service),
   CONSTRAINT uq_service_chef UNIQUE(chef_id),
   CONSTRAINT uq_service_libelle UNIQUE NULLS NOT DISTINCT(service_parent, libelle),
   CONSTRAINT fk_service_parent FOREIGN KEY(service_parent) REFERENCES service(code_service) ON DELETE SET NULL
);

CREATE TABLE Personnel(
   matricule BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
   nom VARCHAR(80) NOT NULL CHECK (nom <> ''),
   prenom VARCHAR(80),
   email VARCHAR(254),
   fonction VARCHAR(20) NOT NULL CONSTRAINT ck_personnel_fonction CHECK (fonction IN ('MEDECIN', 'INFIRMIER', 'ADMIN')),
   code_service VARCHAR(6) NOT NULL CHECK (code_service <> ''),
   date_embauche TIMESTAMP(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL,
   est_cadre SMALLINT DEFAULT 0 NOT NULL CONSTRAINT ck_personnel_cadre CHECK (est_cadre IN (0, 1)),
   salaire DOUBLE PRECISION,
   photo BYTEA,
   CONSTRAINT pk_personnel PRIMARY KEY(matricule),
   CONSTRAINT fk_personnel_service FOREIGN KEY(code_service) REFERENCES service(code_service)
);

CREATE TABLE "Patient"(
   id UUID DEFAULT gen_random_uuid(),
   nir CHAR(15) NOT NULL CHECK (nir <> ''),
   nom VARCHAR(80) NOT NULL CHECK (nom <> ''),
   date_naissance TIMESTAMP(0) NOT NULL,
   sexe CHAR(1) CONSTRAINT ck_patient_sexe CHECK (sexe IN ('M', 'F', 'X')),
   medecin_traitant BIGINT,
   "Note libre" TEXT,
   cree_le TIMESTAMPTZ(3) DEFAULT CURRENT_TIMESTAMP NOT NULL,
   cree_par VARCHAR(128) DEFAULT CURRENT_USER NOT NULL CHECK (cree_par <> ''),
   CONSTRAINT pk_patient PRIMARY KEY(id),
   CONSTRAINT uq_patient_nir UNIQUE(nir),
   CONSTRAINT fk_patient_medecin FOREIGN KEY(medecin_traitant) REFERENCES Personnel(matricule) ON DELETE SET NULL
);

CREATE TABLE sejour(
   sejour_id BIGINT DEFAULT nextval('seq_sejour'),
   patient_id UUID NOT NULL,
   code_service VARCHAR(6) NOT NULL CHECK (code_service <> ''),
   date_entree TIMESTAMP(0) NOT NULL,
   date_sortie TIMESTAMP(0),
   duree_prevue INTERVAL DAY TO SECOND(0),
   date_sortie_prevue TIMESTAMP(0) GENERATED ALWAYS AS ((date_entree + duree_prevue)) VIRTUAL,
   motif VARCHAR(4000),
   CONSTRAINT pk_sejour PRIMARY KEY(sejour_id),
   CONSTRAINT ck_sejour_dates CHECK (date_sortie IS NULL OR date_sortie >= date_entree),
   CONSTRAINT fk_sejour_patient FOREIGN KEY(patient_id) REFERENCES "Patient"(id) ON DELETE CASCADE,
   CONSTRAINT fk_sejour_service FOREIGN KEY(code_service) REFERENCES service(code_service)
);

CREATE TABLE intervenir(
   sejour_id BIGINT,
   matricule BIGINT,
   type VARCHAR(15) DEFAULT 'soin' NOT NULL CONSTRAINT ck_intervenir_type CHECK (type IN ('consult', 'chirurgie', 'soin')),
   debut TIMESTAMP(0),
   duree INTERVAL DAY TO SECOND(0),
   superviseur BIGINT,
   cout NUMERIC(8,2),
   CONSTRAINT pk_intervenir PRIMARY KEY(sejour_id, matricule, debut),
   CONSTRAINT fk_intervenir_sejour FOREIGN KEY(sejour_id) REFERENCES sejour(sejour_id) ON DELETE CASCADE,
   CONSTRAINT fk_intervenir_personnel FOREIGN KEY(matricule) REFERENCES Personnel(matricule),
   CONSTRAINT fk_intervenir_superviseur FOREIGN KEY(superviseur) REFERENCES Personnel(matricule) ON DELETE SET NULL
);
