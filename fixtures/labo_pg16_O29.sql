CREATE TABLE chercheur(
   id_chercheur INTEGER GENERATED BY DEFAULT AS IDENTITY,
   nom VARCHAR(50) NOT NULL,
   prenom VARCHAR(50),
   email VARCHAR(120) NOT NULL UNIQUE,
   grade TEXT DEFAULT 'doctorant' CHECK (grade IN ('doctorant', 'MCF', 'PR', 'DR')),
   date_embauche DATE,
   id_mentor INTEGER,
   labo_code CHAR(6),
   labo_site VARCHAR(30),
   PRIMARY KEY(id_chercheur),
   FOREIGN KEY(id_mentor) REFERENCES chercheur(id_chercheur) ON DELETE SET NULL
);

CREATE TABLE "Laboratoire"(
   code_labo CHAR(6),
   site VARCHAR(30),
   nom_labo VARCHAR(100) NOT NULL,
   budget NUMERIC(12,2) CHECK (budget >= 0),
   id_directeur INTEGER NOT NULL UNIQUE,
   PRIMARY KEY(code_labo, site),
   FOREIGN KEY(id_directeur) REFERENCES chercheur(id_chercheur) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE projet(
   id_projet INTEGER,
   titre VARCHAR(200) NOT NULL,
   acronyme VARCHAR(20),
   date_debut DATE NOT NULL,
   date_fin DATE,
   code_labo CHAR(6) NOT NULL,
   site VARCHAR(30) NOT NULL,
   id_responsable INTEGER NOT NULL,
   id_coresponsable INTEGER,
   CONSTRAINT pk_projet PRIMARY KEY(id_projet),
   CONSTRAINT uq_projet_acronyme UNIQUE(acronyme, code_labo, site),
   CONSTRAINT ck_projet_dates CHECK (date_fin IS NULL OR date_fin > date_debut),
   CONSTRAINT ck_resp_distincts CHECK (id_coresponsable <> id_responsable),
   CONSTRAINT fk_projet_labo FOREIGN KEY(code_labo, site) REFERENCES "Laboratoire"(code_labo, site),
   CONSTRAINT fk_projet_resp FOREIGN KEY(id_responsable) REFERENCES chercheur(id_chercheur),
   CONSTRAINT fk_projet_coresp FOREIGN KEY(id_coresponsable) REFERENCES chercheur(id_chercheur)
);

CREATE TABLE phase(
   id_projet INTEGER,
   num_phase SMALLINT CHECK (num_phase > 0),
   libelle VARCHAR(80) NOT NULL,
   duree_semaines INTEGER,
   num_phase_precedente SMALLINT,
   PRIMARY KEY(id_projet, num_phase),
   FOREIGN KEY(id_projet) REFERENCES projet(id_projet) ON DELETE CASCADE,
   FOREIGN KEY(id_projet, num_phase_precedente) REFERENCES phase(id_projet, num_phase)
);

CREATE TABLE participer(
   id_chercheur INTEGER,
   id_projet INTEGER,
   num_phase SMALLINT,
   code_labo CHAR(6) NOT NULL,
   site VARCHAR(30) NOT NULL,
   role VARCHAR(30) DEFAULT 'contributeur',
   taux_implication DOUBLE PRECISION CHECK (taux_implication > 0 AND taux_implication <= 1),
   date_affectation DATE DEFAULT CURRENT_DATE,
   PRIMARY KEY(id_chercheur, id_projet, num_phase),
   FOREIGN KEY(id_chercheur) REFERENCES chercheur(id_chercheur) ON DELETE CASCADE,
   FOREIGN KEY(id_projet, num_phase) REFERENCES phase(id_projet, num_phase) ON DELETE CASCADE,
   FOREIGN KEY(code_labo, site) REFERENCES "Laboratoire"(code_labo, site)
);

ALTER TABLE chercheur ADD CONSTRAINT fk_chercheur_labo FOREIGN KEY(labo_code, labo_site) REFERENCES "Laboratoire"(code_labo, site);

CREATE INDEX ix_participer_labo ON participer(code_labo, site);
