CREATE TABLE adherent(
   id INTEGER GENERATED BY DEFAULT AS IDENTITY,
   num_carte CHAR(10) NOT NULL UNIQUE,
   nom VARCHAR(100) NOT NULL,
   email VARCHAR(255) NOT NULL,
   parrain_id INTEGER,
   statut TEXT DEFAULT 'actif' NOT NULL,
   centres_interet TEXT,
   est_mineur BOOLEAN DEFAULT 0 NOT NULL,
   cree_le TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
   maj_le TIMESTAMP DEFAULT NULL,
   PRIMARY KEY(id),
   CONSTRAINT uq_email_prefixe UNIQUE(email),
   FOREIGN KEY(parrain_id) REFERENCES adherent(id) ON DELETE SET NULL
);

CREATE TABLE oeuvre(
   id_oeuvre INTEGER GENERATED BY DEFAULT AS IDENTITY,
   isbn CHAR(13) COLLATE ascii_bin NOT NULL,
   titre VARCHAR(255) NOT NULL,
   type TEXT NOT NULL,
   annee TEXT CONSTRAINT ck_annee CHECK (annee IS NULL OR annee >= 1901),
   prix_ht NUMERIC(8,2),
   prix_ttc NUMERIC(8,2),
   "desc" TEXT,
   recommandee_par INTEGER,
   oeuvre_id INTEGER,
   PRIMARY KEY(id_oeuvre),
   CONSTRAINT uq_isbn UNIQUE(isbn),
   CONSTRAINT fk_oeuvre_vo FOREIGN KEY(oeuvre_id) REFERENCES oeuvre(id_oeuvre) ON DELETE SET NULL
);

CREATE TABLE adherent_premium(
   adherent_id INTEGER,
   niveau SMALLINT DEFAULT 1 NOT NULL CONSTRAINT ck_niveau CHECK (niveau BETWEEN 1 AND 3),
   date_souscription DATE NOT NULL,
   cotisation NUMERIC(6,2) NOT NULL,
   oeuvre_favorite INTEGER,
   PRIMARY KEY(adherent_id),
   CONSTRAINT fk_premium_adherent FOREIGN KEY(adherent_id) REFERENCES adherent(id) ON DELETE CASCADE ON UPDATE CASCADE,
   CONSTRAINT fk_premium_favori FOREIGN KEY(oeuvre_favorite) REFERENCES oeuvre(id_oeuvre) ON DELETE SET NULL
);

CREATE TABLE "Exemplaire"(
   id_oeuvre INTEGER,
   num_ex SMALLINT,
   code_barre VARCHAR(20) NOT NULL,
   etat TEXT DEFAULT 'neuf',
   date_acquisition DATE,
   PRIMARY KEY(id_oeuvre, num_ex),
   CONSTRAINT ix_ex_oeuvre FOREIGN KEY(id_oeuvre) REFERENCES oeuvre(id_oeuvre) ON DELETE CASCADE
);

CREATE TABLE emprunt(
   adherent_id INTEGER,
   id_oeuvre INTEGER,
   num_ex SMALLINT,
   date_emprunt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   date_retour_prevue DATE,
   date_retour TIMESTAMP,
   penalite NUMERIC(5,2) DEFAULT 0.00 NOT NULL CONSTRAINT ck_penalite CHECK (penalite >= 0),
   details JSON,
   remarque VARCHAR(500) COLLATE utf8mb4_bin,
   PRIMARY KEY(adherent_id, id_oeuvre, num_ex, date_emprunt),
   CONSTRAINT ck_retour CHECK (date_retour IS NULL OR date_retour >= date_emprunt),
   CONSTRAINT fk_emprunt_adherent FOREIGN KEY(adherent_id) REFERENCES adherent(id),
   CONSTRAINT fk_emprunt_ex FOREIGN KEY(id_oeuvre, num_ex) REFERENCES "Exemplaire"(id_oeuvre, num_ex) ON UPDATE CASCADE
);

