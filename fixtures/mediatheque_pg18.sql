-- Rapport de conversion vers PostgreSQL 18 : 11 élément(s) abandonné(s) ou dégradé(s)
--   • ENUM sous collation insensible : une valeur saisie dans une autre casse (ACTIF) est acceptée telle quelle, MySQL la ramenait à la valeur de l'ENUM (actif) : adherent.statut, oeuvre.type, Exemplaire.etat
--   • adherent.centres_interet — SET → TEXT[] : l'ordre et les doublons, normalisés par MySQL, sont conservés tels que saisis
--   • adherent.est_mineur — TINYINT(1) → BOOLEAN : MySQL y accepte d'autres valeurs que 0 / 1 (de −128 à 127) ; seuls vrai / faux restent
--   • TIMESTAMP MySQL (UTC, plage 1970–2038) → TIMESTAMPTZ : même sémantique de fuseau, plage plus large : adherent.cree_le, adherent.maj_le
--   • adherent.maj_le — ON UPDATE CURRENT_TIMESTAMP non traduit : un déclencheur serait nécessaire
--   • Exemplaire — méthode d'index HASH de uq_code_barre abandonnée (l'index ou la contrainte sont conservés)
--   • emprunt — déclencheur trg_emprunt_statut non traduit (code propre au SGBD d'origine)
--   • oeuvre — index plein texte ft_titre → index GIN sur to_tsvector('simple', …) : approximation (requêtes MATCH … AGAINST à réécrire)

CREATE COLLATION IF NOT EXISTS merise_ai_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE TABLE adherent(
   id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) CHECK (id >= 0),
   num_carte CHAR(10) COLLATE merise_ai_ci NOT NULL UNIQUE,
   nom VARCHAR(100) COLLATE merise_ai_ci NOT NULL,
   email VARCHAR(255) COLLATE merise_ai_ci NOT NULL,
   parrain_id BIGINT,
   statut VARCHAR(8) COLLATE merise_ai_ci DEFAULT 'actif' NOT NULL CHECK (statut IN ('actif', 'suspendu', 'radié')),
   centres_interet TEXT[] COLLATE merise_ai_ci CHECK (centres_interet <@ ARRAY['roman', 'bd', 'jeunesse', 'sf', 'essai']::text[]),
   est_mineur BOOLEAN DEFAULT FALSE NOT NULL,
   cree_le TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
   maj_le TIMESTAMPTZ,
   PRIMARY KEY(id),
   FOREIGN KEY(parrain_id) REFERENCES adherent(id) ON DELETE SET NULL
);

CREATE TABLE oeuvre(
   id_oeuvre BIGINT GENERATED BY DEFAULT AS IDENTITY CHECK (id_oeuvre >= 0),
   isbn CHAR(13) COLLATE "C" NOT NULL,
   titre VARCHAR(255) COLLATE merise_ai_ci NOT NULL,
   type VARCHAR(5) COLLATE merise_ai_ci NOT NULL CHECK (type IN ('livre', 'bd', 'dvd', 'cd')),
   annee SMALLINT CONSTRAINT ck_annee CHECK ((annee IS NULL OR annee >= 1901) AND annee BETWEEN 1901 AND 2155),
   prix_ht NUMERIC(8,2) CHECK (prix_ht >= 0),
   prix_ttc NUMERIC(8,2) GENERATED ALWAYS AS (ROUND((prix_ht * 1.055), 2)) STORED,
   isbn_originale CHAR(13) COLLATE "C",
   "desc" TEXT COLLATE merise_ai_ci,
   recommandee_par BIGINT,
   PRIMARY KEY(id_oeuvre),
   CONSTRAINT uq_isbn UNIQUE(isbn),
   CONSTRAINT fk_oeuvre_vo FOREIGN KEY(isbn_originale) REFERENCES oeuvre(isbn) ON DELETE SET NULL
);

CREATE TABLE adherent_premium(
   adherent_id BIGINT,
   niveau SMALLINT DEFAULT 1 NOT NULL CONSTRAINT ck_niveau CHECK (niveau BETWEEN 1 AND 3),
   date_souscription DATE NOT NULL,
   cotisation NUMERIC(6,2) NOT NULL,
   oeuvre_favorite BIGINT,
   PRIMARY KEY(adherent_id),
   CONSTRAINT fk_premium_adherent FOREIGN KEY(adherent_id) REFERENCES adherent(id) ON DELETE CASCADE ON UPDATE CASCADE,
   CONSTRAINT fk_premium_favori FOREIGN KEY(oeuvre_favorite) REFERENCES oeuvre(id_oeuvre) ON DELETE SET NULL
);

CREATE TABLE "Exemplaire"(
   id_oeuvre BIGINT,
   num_ex INTEGER CHECK (num_ex >= 0),
   code_barre VARCHAR(20) COLLATE merise_ai_ci NOT NULL,
   etat VARCHAR(7) COLLATE merise_ai_ci DEFAULT 'neuf' CHECK (etat IN ('neuf', 'bon', 'abîmé', 'pilonné')),
   date_acquisition DATE,
   PRIMARY KEY(id_oeuvre, num_ex),
   CONSTRAINT uq_code_barre UNIQUE(code_barre),
   CONSTRAINT fk_ex_oeuvre FOREIGN KEY(id_oeuvre) REFERENCES oeuvre(id_oeuvre) ON DELETE CASCADE
);

CREATE TABLE emprunt(
   adherent_id BIGINT,
   id_oeuvre BIGINT,
   num_ex INTEGER,
   date_emprunt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   date_retour_prevue DATE GENERATED ALWAYS AS ((date_emprunt::date + 21)) VIRTUAL,
   date_retour TIMESTAMP,
   penalite NUMERIC(5,2) DEFAULT 0.00 NOT NULL CONSTRAINT ck_penalite CHECK (penalite >= 0),
   details JSONB,
   remarque VARCHAR(500) COLLATE "C",
   PRIMARY KEY(adherent_id, id_oeuvre, num_ex, date_emprunt),
   CONSTRAINT ck_retour CHECK (date_retour IS NULL OR date_retour >= date_emprunt),
   CONSTRAINT fk_emprunt_adherent FOREIGN KEY(adherent_id) REFERENCES adherent(id),
   CONSTRAINT fk_emprunt_ex FOREIGN KEY(id_oeuvre, num_ex) REFERENCES "Exemplaire"(id_oeuvre, num_ex) ON UPDATE CASCADE
);

ALTER TABLE oeuvre ADD CONSTRAINT fk_oeuvre_reco FOREIGN KEY(recommandee_par) REFERENCES adherent_premium(adherent_id) ON DELETE SET NULL;

CREATE INDEX ix_parrain ON adherent(parrain_id);

CREATE INDEX ft_titre ON oeuvre USING GIN (to_tsvector('simple', titre));

CREATE INDEX ix_favori ON adherent_premium(oeuvre_favorite);

CREATE INDEX ix_emprunt_ex ON emprunt(id_oeuvre, num_ex, date_retour);

CREATE UNIQUE INDEX uq_email_prefixe ON adherent(left(email, 100));

COMMENT ON TABLE adherent IS 'Adhérents; parrain_id porte un REFERENCES « inline »';

COMMENT ON COLUMN oeuvre.prix_ht IS 'Prix HT -- hors remise; voir /* règle 3 */ l''ancien barème';

COMMENT ON COLUMN oeuvre.isbn_originale IS 'Traduction de l''œuvre ("VO")';
